use std::path::Path;

/// 为没有 Favicon 的网站生成现代感首字母彩色徽标（如 5312 -> "5"，github -> "G"）
pub fn generate_fallback_letter_icon(domain: &str, output_png: &Path) -> bool {
    let mut img = image::RgbaImage::new(64, 64);

    let palettes = [
        [0x02, 0x84, 0xc7, 0xff], // 海天蓝
        [0x4f, 0x46, 0xe5, 0xff], // 经典靛蓝
        [0x7c, 0x3a, 0xed, 0xff], // 优雅紫罗兰
        [0x05, 0x96, 0x69, 0xff], // 翡翠绿
        [0xd9, 0x77, 0x06, 0xff], // 暖琥珀
        [0xdb, 0x27, 0x77, 0xff], // 蔷薇粉
    ];
    let hash_bytes = domain.as_bytes();
    let color_idx = hash_bytes.iter().map(|b| *b as usize).sum::<usize>() % palettes.len();
    let bg = palettes[color_idx];

    // 绘制 64x64 柔和平滑大圆角卡片
    for y in 0..64 {
        for x in 0..64 {
            let dx = (x as i32 - 32).abs();
            let dy = (y as i32 - 32).abs();
            let inside = if dx > 18 && dy > 18 {
                let rx = dx - 18;
                let ry = dy - 18;
                rx * rx + ry * ry <= 14 * 14
            } else {
                dx <= 28 && dy <= 28
            };

            if inside {
                img.put_pixel(x, y, image::Rgba(bg));
            }
        }
    }

    let first_char = domain
        .chars()
        .find(|c| c.is_alphanumeric())
        .unwrap_or('W')
        .to_ascii_uppercase();

    // 绘制首字符白光点阵
    draw_letter_5x7(&mut img, first_char);

    img.save_with_format(output_png, image::ImageFormat::Png)
        .is_ok()
}

/// 绘制中心 5x7 放大点阵字符
fn draw_letter_5x7(img: &mut image::RgbaImage, ch: char) {
    let glyph: [u8; 7] = match ch {
        '0' => [0x0e, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0e],
        '1' => [0x04, 0x0c, 0x04, 0x04, 0x04, 0x04, 0x0e],
        '2' => [0x0e, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1f],
        '3' => [0x1f, 0x02, 0x04, 0x06, 0x01, 0x11, 0x0e],
        '4' => [0x02, 0x06, 0x0a, 0x12, 0x1f, 0x02, 0x02],
        '5' => [0x1f, 0x10, 0x1e, 0x01, 0x01, 0x11, 0x0e],
        '6' => [0x06, 0x08, 0x10, 0x1e, 0x11, 0x11, 0x0e],
        '7' => [0x1f, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0e, 0x11, 0x11, 0x0e, 0x11, 0x11, 0x0e],
        '9' => [0x0e, 0x11, 0x11, 0x0f, 0x01, 0x02, 0x0c],
        'A' => [0x04, 0x0a, 0x11, 0x11, 0x1f, 0x11, 0x11],
        'B' => [0x1e, 0x11, 0x11, 0x1e, 0x11, 0x11, 0x1e],
        'C' => [0x0e, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0e],
        'D' => [0x1c, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1c],
        'E' => [0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x1f],
        'F' => [0x1f, 0x10, 0x10, 0x1e, 0x10, 0x10, 0x10],
        'G' => [0x0e, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0f],
        'H' => [0x11, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x11],
        'I' => [0x0e, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0e],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0c],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1f],
        'M' => [0x11, 0x1b, 0x15, 0x11, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11],
        'O' => [0x0e, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
        'P' => [0x1e, 0x11, 0x11, 0x1e, 0x10, 0x10, 0x10],
        'Q' => [0x0e, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0d],
        'R' => [0x1e, 0x11, 0x11, 0x1e, 0x14, 0x12, 0x11],
        'S' => [0x0f, 0x10, 0x10, 0x0e, 0x01, 0x01, 0x1e],
        'T' => [0x1f, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0a, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x1b, 0x11],
        'X' => [0x11, 0x11, 0x0a, 0x04, 0x0a, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x0a, 0x04, 0x04, 0x04, 0x04],
        'Z' => [0x1f, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1f],
        _ => [0x00, 0x00, 0x0e, 0x0e, 0x0e, 0x00, 0x00],
    };

    let scale = 4;
    let offset_x = (64 - 5 * scale) / 2;
    let offset_y = (64 - 7 * scale) / 2;
    let white = image::Rgba([0xff, 0xff, 0xff, 0xff]);

    for (row_idx, &row_val) in glyph.iter().enumerate() {
        for col_idx in 0..5 {
            let bit = (row_val >> (4 - col_idx)) & 1;
            if bit == 1 {
                for sy in 0..scale {
                    for sx in 0..scale {
                        let px = (offset_x + col_idx * scale + sx) as u32;
                        let py = (offset_y + row_idx as i32 * scale + sy) as u32;
                        if px < 64 && py < 64 {
                            img.put_pixel(px, py, white);
                        }
                    }
                }
            }
        }
    }
}
